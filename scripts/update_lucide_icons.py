#!/usr/bin/env python3
"""Vendor Lucide SVGs and generate Rust constants (Python standard library only).

With no arguments, reproduce the checked-in revision. Use --ref main or a tag
to update. Downloads happen only when maintaining the library, never at build time.
"""

import argparse
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile
from urllib.parse import quote
from urllib.request import Request, urlopen
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "lucide"


def download(url):
    request = Request(url, headers={"User-Agent": "egui-component-lucide-sync"})
    with urlopen(request, timeout=120) as response:
        return response.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", help="Upstream commit, tag or branch")
    args = parser.parse_args()
    manifest = ASSETS / "source.json"
    ref = args.ref or (json.loads(manifest.read_text())["commit"] if manifest.exists() else "main")
    if re.fullmatch(r"[0-9a-f]{40}", ref):
        commit = ref
    else:
        commit = json.loads(download(
            "https://api.github.com/repos/lucide-icons/lucide/commits/" + quote(ref, safe="")
        ))["sha"]
    archive = download(f"https://codeload.github.com/lucide-icons/lucide/tar.gz/{commit}")
    icons = {}
    license_text = None
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as tar:
        for member in tar.getmembers():
            relative = member.name.split("/", 1)[-1]
            if not member.isfile():
                continue
            if relative == "LICENSE":
                license_text = tar.extractfile(member).read().decode()
            if re.fullmatch(r"icons/[a-z0-9-]+\.svg", relative):
                name = Path(relative).stem
                svg = tar.extractfile(member).read().decode().replace("currentColor", "#ffffff")
                if ET.fromstring(svg).tag != "{http://www.w3.org/2000/svg}svg":
                    raise ValueError(f"Invalid SVG: {name}")
                icons[name] = svg
    if not icons or not license_text:
        raise ValueError("Archive is missing icons or LICENSE")
    lines = [
        "// Generated by scripts/update_lucide_icons.py. Do not edit.",
        "//! Lucide SVGs for egui tinting. Enable the `lucide_icon` feature.",
        "//! Example: `egui_component::icon::lucide::HEART`.",
        "", 
    ]
    identifiers = set()
    for name in sorted(icons):
        ident = name.replace("-", "_").upper()
        if ident[0].isdigit():
            ident = "ICON_" + ident
        if ident in identifiers:
            raise ValueError(f"Duplicate identifier: {ident}")
        identifiers.add(ident)
        lines += [f"/// Lucide `{name}`.", f'pub const {ident}: egui::ImageSource<\'static> = egui::include_image!("../../assets/lucide/{name}.svg");']
    lines += ["", "/// All upstream icon names, in sorted order.", "pub const NAMES: &[&str] = &["]
    lines += [f'    "{name}",' for name in sorted(icons)]
    lines += ["];", "", "/// Look up an icon by its upstream kebab-case name.", "pub fn get(name: &str) -> Option<egui::ImageSource<'static>> {", "    match name {"]
    for name in sorted(icons):
        ident = name.replace("-", "_").upper()
        if ident[0].isdigit():
            ident = "ICON_" + ident
        lines.append(f'        "{name}" => Some({ident}),')
    lines += ["        _ => None,", "    }", "}", ""]
    ASSETS.mkdir(parents=True, exist_ok=True)
    for name, svg in icons.items():
        (ASSETS / f"{name}.svg").write_text(svg)
    for old in ASSETS.glob("*.svg"):
        if old.stem not in icons:
            old.unlink()
    (ASSETS / "LICENSE").write_text(license_text)
    manifest.write_text(json.dumps({"repository": "https://github.com/lucide-icons/lucide", "commit": commit, "icon_count": len(icons), "modification": "currentColor replaced with #ffffff"}, indent=2) + "\n")
    module = ROOT / "src" / "icon" / "lucide.rs"
    module.parent.mkdir(parents=True, exist_ok=True)
    module.write_text("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2024", str(module)], check=True)
    print(f"Vendored {len(icons)} Lucide icons at {commit}")


if __name__ == "__main__":
    main()
